def build_bakery_dataset_contract(
    confirmation: TargetConfirmation | None = None,
) -> DatasetContract:
    """Build the DatasetContract for bakery pre-production waste prediction."""

    features = (
        FeatureContract(
            name="factory_id",
            display_name="Factory Identifier",
            description="Unique factory identifier for tenant isolation.",
            data_type=DataType.STRING,
            role=FeatureRole.IDENTIFIER,
            availability=FeatureAvailability.STATIC,
            origin=FeatureOrigin.CONFIGURED,
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("plant_id", "site_id"),
            source_system="ERP",
        ),
        FeatureContract(
            name="batch_id",
            display_name="Batch Identifier",
            description="Unique production batch or order identifier.",
            data_type=DataType.STRING,
            role=FeatureRole.IDENTIFIER,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.RECORDED,
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("order_id", "lot_number"),
            source_system="ERP",
        ),
        FeatureContract(
            name="production_timestamp",
            display_name="Planned Production Timestamp",
            description="Scheduled start timestamp of the bakery batch.",
            data_type=DataType.DATETIME,
            role=FeatureRole.TIMESTAMP,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.RECORDED,
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("scheduled_date", "shift_start_ts"),
            source_system="ERP",
        ),
        FeatureContract(
            name="production_line_id",
            display_name="Production Line ID",
            description="Assigned bakery line or oven line identifier.",
            data_type=DataType.CATEGORY,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.CONFIGURED,
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("line_id",),
            source_system="MES",
        ),
        FeatureContract(
            name="product_category",
            display_name="Product Category",
            description="Standardized bakery product family (e.g., white_bread, pastry, biscuit).",
            data_type=DataType.CATEGORY,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.CONFIGURED,
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("sku_family", "pr_group"),
            source_system="ERP",
        ),
        FeatureContract(
            name="planned_batch_quantity_kg",
            display_name="Planned Batch Quantity (kg)",
            description="Scheduled dough/product output mass for the batch.",
            data_type=DataType.FLOAT,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.RECORDED,
            unit="kg",
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("planned_qty_kg", "target_mass_kg", "batch_size_kg"),
            constraints=FeatureConstraints(minimum=0.0, minimum_inclusive=False),
            source_system="ERP",
        ),
        FeatureContract(
            name="planned_raw_material_kg",
            display_name="Planned Raw Material Mass (kg)",
            description="Total planned ingredient mass before baking.",
            data_type=DataType.FLOAT,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.RECORDED,
            unit="kg",
            required=False,
            nullable=True,
            missing_policy=MissingValuePolicy.IMPUTE,
            aliases=("raw_material_kg",),
            constraints=FeatureConstraints(minimum=0.0, minimum_inclusive=False),
            source_system="ERP",
        ),
        FeatureContract(
            name="planned_processing_temp_c",
            display_name="Planned Oven Setpoint Temperature (degC)",
            description="Target baking oven setpoint temperature.",
            data_type=DataType.FLOAT,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.CONFIGURED,
            unit="degC",
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("oven_temp_c", "setpoint_temp_c"),
            constraints=FeatureConstraints(minimum=20.0, maximum=320.0),
            source_system="MES",
        ),
        FeatureContract(
            name="planned_processing_duration_min",
            display_name="Planned Baking Duration (min)",
            description="Scheduled oven residence time.",
            data_type=DataType.FLOAT,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.CONFIGURED,
            unit="min",
            required=True,
            nullable=False,
            missing_policy=MissingValuePolicy.REJECT,
            aliases=("baking_time_min", "duration_pt"),
            constraints=FeatureConstraints(minimum=0.0, minimum_inclusive=False),
            source_system="MES",
        ),
        FeatureContract(
            name="planned_shift",
            display_name="Planned Shift",
            description="Scheduled production shift.",
            data_type=DataType.CATEGORY,
            role=FeatureRole.PREDICTOR,
            availability=FeatureAvailability.PRE_PRODUCTION,
            origin=FeatureOrigin.RECORDED,
            required=False,
            nullable=True,
            missing_policy=MissingValuePolicy.ALLOW,
            constraints=FeatureConstraints(allowed_values=("morning", "afternoon", "night")),
            source_system="MES",
        ),
        FeatureContract(
            name="actual_yield_pct",
            display_name="Realized Production Yield (%)",
            description="Post-production yield KPI; prohibited as pre-production predictor.",
            data_type=DataType.FLOAT,
            role=FeatureRole.METADATA,
            availability=FeatureAvailability.POST_PRODUCTION,
            origin=FeatureOrigin.DERIVED,
            unit="%",
            required=False,
            nullable=True,
            missing_policy=MissingValuePolicy.ALLOW,
            derived_from=("planned_batch_quantity_kg",),
            source_system="MES",
        ),
    )

    target_feature = FeatureContract(
        name="waste_quantity_kg",
        display_name="Avoidable Bakery Waste (kg)",
        description="Measured avoidable dough/baked product scrap and rejected loaves.",
        data_type=DataType.FLOAT,
        role=FeatureRole.TARGET,
        availability=FeatureAvailability.POST_PRODUCTION,
        origin=FeatureOrigin.MEASURED,
        unit="kg",
        required=True,
        nullable=False,
        missing_policy=MissingValuePolicy.REJECT,
        aliases=("scrap_kg", "reject_weight_kg", "material_loss_kg"),
        constraints=FeatureConstraints(minimum=0.0),
        source_system="Floor Scale / QC Log",
    )

    target = TargetContract(
        target_id="waste_quantity_kg",
        version="1.0.0",
        feature=target_feature,
        task_type=TaskType.REGRESSION,
        target_kind=TargetKind.QUANTITY,
        definition=TargetDefinition(
            definition=(
                "Total mass (kg) of avoidable bakery material waste and rejected finished units "
                "generated during mixing, proofing, baking, and packaging."
            ),
            granularity="batch",
            measurement_method="Calibrated floor waste bin scale and QC reject weigh-out",
            included_components=(
                "spoiled_dough",
                "burnt_or_collapsed_batches",
                "slicing_trim_scrap",
                "qc_rejected_loaves",
            ),
            excluded_components=(
                "baking_moisture_evaporation",
                "rework_dough_reused",
                "recoverable_animal_feed_byproduct",
                "packaging_film_scrap",
            ),
        ),
        confirmation=confirmation or TargetConfirmation(),
        derived_rate=RateDefinition(
            name="waste_rate_pct",
            numerator="waste_quantity_kg",
            denominator="planned_batch_quantity_kg",
            granularity="batch",
            output_unit="%",
            multiplier=100.0,
        ),
    )

    return DatasetContract(
        dataset_id="food_beverage_bakery_waste_v1",
        version="1.0.0",
        domain="food_beverage",
        process=PROCESS_ID,
        description="Pre-production avoidable waste contract for bakery manufacturing.",
        granularity="batch",
        features=features,
        target=target,
        prediction_context=PredictionContext(
            prediction_stage=FeatureAvailability.PRE_PRODUCTION,
            horizon_seconds=0,
            description="Pre-production prediction made before batch mixing/baking starts.",
        ),
        business_keys=("factory_id", "batch_id"),
        grouping_columns=("batch_id",),
        time_column="production_timestamp",
    )


def build_bakery_process_contract(
    confirmation: TargetConfirmation | None = None,
) -> ProcessContract:
    """Build the ProcessContract for bakery manufacturing."""

    dataset_contract = build_bakery_dataset_contract(confirmation=confirmation)
    task = IndustrialTaskContract(
        task_id=TASK_ID,
        version="1.0.0",
        display_name="Bakery Pre-Production Waste Prediction (kg)",
        description="Predict avoidable batch waste mass (kg) prior to bakery production.",
        module=PlatformModule.WASTE_MANAGEMENT,
        task_type=TaskType.REGRESSION,
        dataset_contract=dataset_contract,
    )
    return ProcessContract(
        process_id=PROCESS_ID,
        version="1.0.0",
        display_name="Bakery & Cereal Manufacturing",
        description="Industrial bread, pastry, and baked goods manufacturing process.",
        tasks=(task,),
    )
