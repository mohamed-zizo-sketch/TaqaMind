"""Deterministic synthetic dataset generators for offline testing and CLI demos.

IMPORTANT:
    All records generated by this module are explicitly synthetic fixtures for
    software verification. They do NOT represent real Egyptian factory data and
    must NEVER be cited as industrial production validation evidence.
"""

from __future__ import annotations

from datetime import datetime, timedelta

import numpy as np
import pandas as pd

from taqamind.domains.iron_manufacturing.processes.eaf_meltshop import EAF_PROCESS_ID
from taqamind.domains.iron_manufacturing.processes.rebar_hot_rolling import REBAR_PROCESS_ID
from taqamind.domains.iron_manufacturing.processes.scrap_yard_reception import (
    SCRAP_YARD_PROCESS_ID,
)


def generate_synthetic_eaf_dataset(
    *,
    n_rows: int = 120,
    seed: int = 42,
    include_target: bool = True,
    start_index: int = 1,
    start_date: str = "2026-01-01T06:00:00",
) -> pd.DataFrame:
    """Generate deterministic synthetic EAF meltshop heat records."""
    rng = np.random.default_rng(seed)
    base_ts = datetime.fromisoformat(start_date)

    rows: list[dict[str, object]] = []
    grades = ("B500DWR", "B500B", "A615_G60")
    furnaces = ("EAF_1", "EAF_2")
    shifts = ("MORNING", "EVENING", "NIGHT")
    scrap_mixes = ("HMS1_HEAVY", "SHREDDED_MIX", "LOCAL_LIGHT")

    for i in range(n_rows):
        idx = start_index + i
        order_idx = ((idx - 1) // 6) + 1
        ts = base_ts + timedelta(minutes=75 * i)
        furnace = furnaces[i % len(furnaces)]
        shift = shifts[(ts.hour // 8) % 3]
        grade = grades[int(rng.integers(0, len(grades)))]
        scrap_mix = scrap_mixes[int(rng.integers(0, len(scrap_mixes)))]

        planned_dri = float(np.round(rng.uniform(55.0, 92.0), 2))
        planned_scrap = float(np.round(rng.uniform(18.0, 45.0), 2))
        total_charge = planned_dri + planned_scrap
        planned_tap = float(np.round(total_charge * rng.uniform(0.90, 0.93), 2))
        contam_pct = float(np.round(rng.uniform(0.6, 5.5), 2))
        dri_met = float(np.round(rng.uniform(90.5, 95.0), 2))
        dri_gangue = float(np.round(rng.uniform(3.8, 7.2), 2))
        hot_heel = float(np.round(rng.uniform(8.0, 16.0), 2))
        lime_kg = float(np.round(rng.uniform(3200.0, 5600.0), 1))
        oxygen_nm3 = float(np.round(rng.uniform(2800.0, 4800.0), 1))
        tap_temp = float(np.round(rng.uniform(1610.0, 1655.0), 1))
        lining_age = int((idx % 280) + 1)

        row: dict[str, object] = {
            "heat_id": f"H-{idx:05d}",
            "production_order_id": f"ORD-EAF-{order_idx:04d}",
            "planned_start_ts": ts.isoformat(),
            "furnace_id": furnace,
            "shift_code": shift,
            "steel_grade_code": grade,
            "planned_scrap_mass_t": planned_scrap,
            "planned_dri_mass_t": planned_dri,
            "planned_tap_mass_t": planned_tap,
            "planned_scrap_grade_mix_code": scrap_mix,
            "expected_scrap_contaminant_pct": contam_pct,
            "dri_metallization_pct": dri_met,
            "dri_gangue_pct": dri_gangue,
            "planned_hot_heel_mass_t": hot_heel,
            "planned_lime_flux_kg": lime_kg,
            "planned_oxygen_nm3": oxygen_nm3,
            "target_tap_temp_c": tap_temp,
            "refractory_lining_heat_age": lining_age,
        }

        if include_target:
            # Physically grounded synthetic signal with realistic noise
            loss = (
                0.048 * total_charge
                + 0.014 * planned_scrap * contam_pct
                + 0.24 * (95.0 - dri_met)
                + 0.28 * dri_gangue
                + 0.00045 * oxygen_nm3
                + 0.0003 * lime_kg
                + 0.015 * max(0.0, tap_temp - 1610.0)
                + 0.004 * lining_age
                + (0.35 if scrap_mix == "LOCAL_LIGHT" else 0.0)
                + float(rng.normal(0.0, 0.28))
            )
            row["metallic_waste_loss_t"] = float(np.round(max(0.0, loss), 3))

        rows.append(row)

    return pd.DataFrame(rows)


def generate_synthetic_rebar_dataset(
    *,
    n_rows: int = 120,
    seed: int = 42,
    include_target: bool = True,
    start_index: int = 1,
    start_date: str = "2026-01-01T07:00:00",
) -> pd.DataFrame:
    """Generate deterministic synthetic rebar hot rolling lot records."""
    rng = np.random.default_rng(seed)
    base_ts = datetime.fromisoformat(start_date)

    rows: list[dict[str, object]] = []
    diameters = (10.0, 12.0, 16.0, 20.0, 25.0)
    grades = ("B500DWR", "B500B")
    lines = ("MILL_A", "MILL_B")
    charge_modes = ("HOT_CHARGE", "COLD_CHARGE")

    for i in range(n_rows):
        idx = start_index + i
        order_idx = ((idx - 1) // 6) + 1
        ts = base_ts + timedelta(hours=3 * i)
        dia = float(diameters[int(rng.integers(0, len(diameters)))])
        strands = 3 if dia <= 12.0 else (2 if dia <= 16.0 else 1)
        billet_count = int(rng.integers(35, 95))
        billet_mass_t = float(np.round(billet_count * rng.uniform(1.55, 1.72), 2))
        mode = charge_modes[int(rng.integers(0, len(charge_modes)))]
        reheat_temp = float(np.round(rng.uniform(1110.0, 1195.0), 1))
        groove_age = float(np.round(rng.uniform(100.0, 4200.0), 1))
        mill_speed = float(np.round(rng.uniform(14.0, 32.0), 1))

        row: dict[str, object] = {
            "rolling_lot_id": f"RL-{idx:05d}",
            "production_order_id": f"ORD-RBR-{order_idx:04d}",
            "planned_start_ts": ts.isoformat(),
            "mill_line_id": lines[i % len(lines)],
            "steel_grade_code": grades[int(rng.integers(0, len(grades)))],
            "rebar_diameter_mm": dia,
            "planned_input_billet_mass_t": billet_mass_t,
            "slitting_strands_count": strands,
            "planned_billet_count": billet_count,
            "charging_mode_hot_or_cold": mode,
            "target_reheat_temp_c": reheat_temp,
            "finishing_roll_groove_tonnage_age_t": groove_age,
            "planned_mill_speed_mps": mill_speed,
        }

        if include_target:
            base_rate = (
                0.018
                + (0.0055 if mode == "COLD_CHARGE" else 0.0)
                + 0.0028 * (strands - 1)
                + 0.000018 * max(0.0, reheat_temp - 1100.0)
                + 0.0000016 * groove_age
            )
            waste_kg = billet_mass_t * 1000.0 * base_rate + float(rng.normal(0.0, 95.0))
            row["total_rolling_waste_kg"] = float(np.round(max(0.0, waste_kg), 2))

        rows.append(row)

    return pd.DataFrame(rows)


def generate_synthetic_scrap_yard_dataset(
    *,
    n_rows: int = 120,
    seed: int = 42,
    include_target: bool = True,
    zero_inflated: bool = True,
    start_index: int = 1,
    start_date: str = "2026-01-01T06:00:00",
) -> pd.DataFrame:
    """Generate deterministic synthetic scrap yard delivery records (with optional zeros)."""
    rng = np.random.default_rng(seed)
    base_ts = datetime.fromisoformat(start_date)

    rows: list[dict[str, object]] = []
    suppliers = tuple(f"SUP_{s:02d}" for s in range(1, 21))
    grades = ("ST01_HMS", "ST02_SHRED", "ST08_LIGHT", "ST12_TURN")
    warehouses = ("YARD_N", "YARD_S")
    transports = ("Truck", "Rail car")

    for i in range(n_rows):
        idx = start_index + i
        sup_idx = ((idx - 1) // 6) % len(suppliers)
        supplier = suppliers[sup_idx]
        ts = base_ts + timedelta(hours=2 * i)
        grade = grades[int(rng.integers(0, len(grades)))]
        gross_kg = float(np.round(rng.uniform(14_000.0, 38_000.0), 1))

        row: dict[str, object] = {
            "scrap_delivery_id": f"SY-{idx:05d}",
            "supplier_group_id": f"GRP-{supplier}-{((idx - 1) // 6) + 1:03d}",
            "entry_ts": ts.isoformat(),
            "supplier_code": supplier,
            "scrap_grade_code": grade,
            "gross_delivery_mass_kg": gross_kg,
            "warehouse_zone": warehouses[i % len(warehouses)],
            "transport_mode": transports[int(rng.integers(0, len(transports)))],
        }

        if include_target:
            grade_factor = {
                "ST01_HMS": 0.012,
                "ST02_SHRED": 0.032,
                "ST08_LIGHT": 0.068,
                "ST12_TURN": 0.045,
            }[grade]
            if zero_inflated and float(rng.random()) < 0.22:
                contam = 0.0
            else:
                contam = gross_kg * grade_factor + float(rng.normal(0.0, 65.0))
            row["total_contaminant_kg"] = float(np.round(max(0.0, contam), 2))

        rows.append(row)

    return pd.DataFrame(rows)


def generate_synthetic_dataset(
    process_id: str,
    *,
    n_rows: int = 120,
    seed: int = 42,
    include_target: bool = True,
    start_index: int = 1,
    start_date: str = "2026-01-01T06:00:00",
) -> pd.DataFrame:
    """Dispatch synthetic fixture generation by process_id."""
    if process_id == EAF_PROCESS_ID:
        return generate_synthetic_eaf_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date,
        )
    if process_id == REBAR_PROCESS_ID:
        return generate_synthetic_rebar_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date,
        )
    if process_id == SCRAP_YARD_PROCESS_ID:
        return generate_synthetic_scrap_yard_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date,
        )
    raise KeyError(f"Unsupported process_id '{process_id}'.")
