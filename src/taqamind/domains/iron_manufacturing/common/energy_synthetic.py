def generate_synthetic_iron_energy_dataset(
    process_id: str,
    *,
    n_rows: int = 80,
    seed: int = 42,
    include_target: bool = True,
    start_index: int = 0,
    start_date: str | None = None,
    leak_column: str | None = None,
) -> pd.DataFrame:
    """Dispatch V2 energy synthetic fixture generation by process_id."""
    if process_id == EAF_PROCESS_ID:
        return generate_synthetic_eaf_energy_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date or "2026-02-01T06:00:00+00:00",
            leak_column=leak_column,
        )
    if process_id == REBAR_PROCESS_ID:
        return generate_synthetic_rebar_energy_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date or "2026-03-01T06:00:00+00:00",
            leak_column=leak_column,
        )
    if process_id == SCRAP_YARD_PROCESS_ID:
        return generate_synthetic_scrap_yard_energy_dataset(
            n_rows=n_rows,
            seed=seed,
            include_target=include_target,
            start_index=start_index,
            start_date=start_date or "2026-04-01T06:00:00+00:00",
            leak_column=leak_column,
        )
    raise ValueError(f"Unsupported iron_manufacturing process '{process_id}'.")


